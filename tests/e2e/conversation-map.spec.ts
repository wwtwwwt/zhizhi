import { expect, test } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import type { ConversationMapData } from '../../shared/conversation-map';

test('large maps scroll on both axes while keeping fixed node spacing', async ({ page, request }) => {
  const session = await (await request.post('/api/sessions', { data: { title: '大地图' } })).json();
  const data: ConversationMapData = { rootStreamId: session.root_stream_id, messages: [], branches: [] };
  for (let index = 0; index < 40; index++) data.messages.push({ id: `root-${index}`, streamId: data.rootStreamId, parentId: index ? `root-${index - 1}` : null, role: 'assistant', kind: 'assistant', status: 'complete', preview: '主消息' });
  for (let index = 0; index < 40; index++) {
    const streamId = `branch-${index}`;
    data.branches.push({ anchor: { id: streamId, stream_id: streamId, source_node_id: 'source', start_offset: index, end_offset: index + 1, selected_text: '分支' }, parentMessageId: 'root-0', parentStreamId: data.rootStreamId });
    data.messages.push({ id: streamId, streamId, parentId: 'root-0', role: 'user', kind: 'note', status: 'complete', preview: '笔记' });
  }
  await page.route(`**/api/sessions/${session.id}/map`, route => route.fulfill({ json: data }));
  await page.goto('/');
  await page.evaluate(id => localStorage.setItem('lastSession', id), session.id);
  await page.reload();
  await page.getByRole('button', { name: '对话地图', exact: true }).click();
  const viewport = page.locator('.conversation-map-scroll');
  await expect(viewport.locator('.conversation-map-node')).toHaveCount(80);
  await viewport.hover();
  await page.mouse.wheel(180, 180);
  await expect.poll(() => viewport.evaluate(element => element.scrollTop)).toBeGreaterThan(0);
  await expect.poll(() => viewport.evaluate(element => element.scrollLeft)).toBeGreaterThan(0);
  const canvas = viewport.locator('.conversation-map-canvas');
  const size = await canvas.boundingBox();
  await page.keyboard.down('Control');
  await page.mouse.wheel(0, -120);
  await page.keyboard.up('Control');
  expect((await canvas.boundingBox())?.width).toBe(size?.width);
  expect((await canvas.boundingBox())?.height).toBe(size?.height);
});

test('map panel opens below topbar, previews dots and navigates root and nested branch messages', async ({ page, request }) => {
  await request.put('/api/settings', { data: { fakeDelay: 0, blurBackdrop: false } });
  const imported = await (await request.post('/api/documents/import', { data: { name: '地图验证.md', markdown: `## 导入文档\n\n${'这是主对话的长文档，用于验证地图定位。'.repeat(200)}`, resources: [] } })).json();
  const root = await (await request.post(`/api/streams/${imported.root_stream_id}/messages`, { data: { text: '主问题', modelId: 'fake', requestId: randomUUID() } })).json();
  await (await request.get(`/api/generations/${root.generationId}/events`)).text();
  const rootStream = await (await request.get(`/api/streams/${root.streamId}`)).json();
  const source = rootStream.messages.at(-1).slots[0].node;
  const branch = await (await request.post('/api/branches', { data: { sourceNodeId: source.id, start: 0, end: 2, selectedText: source.selection_text.slice(0, 2), question: '地图中的分支问题', modelId: 'fake', requestId: randomUUID() } })).json();
  await (await request.get(`/api/generations/${branch.generationId}/events`)).text();
  const branchStream = await (await request.get(`/api/streams/${branch.streamId}`)).json();
  const branchSource = branchStream.messages.at(-1).slots[0].node;
  const note = await (await request.post('/api/branches', { data: { sourceNodeId: branchSource.id, start: 0, end: 2, selectedText: branchSource.selection_text.slice(0, 2), question: '**深层笔记内容**', kind: 'note', requestId: randomUUID() } })).json();
  const map = await (await request.get(`/api/sessions/${imported.id}/map`)).json() as ConversationMapData;
  const noteMessage = map.messages.find(message => message.streamId === note.streamId)!;
  await page.goto('/');
  await page.evaluate(id => localStorage.setItem('lastSession', id), imported.id);
  await page.reload();
  const toggle = page.getByRole('button', { name: '对话地图', exact: true });
  const fade = page.locator('.workspace .conversation-bottom-fade');
  await expect(fade).toHaveCount(1);
  expect(await fade.evaluate(element => getComputedStyle(element).pointerEvents)).toBe('none');
  const fadeBounds = await fade.boundingBox(), readingBounds = await page.locator('.workspace .conversation-scroll').boundingBox();
  expect(Math.abs(fadeBounds!.y + fadeBounds!.height - readingBounds!.y - readingBounds!.height)).toBeLessThan(1);
  const readingBefore = await page.locator('.workspace .conversation-scroll').boundingBox();
  await toggle.click();
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  const panel = page.getByRole('region', { name: '对话地图', exact: true });
  await expect(panel.locator('.conversation-map-node')).toHaveCount(map.messages.length);
  const geometry = await panel.evaluate(element => ({ top: element.getBoundingClientRect().top, header: document.querySelector('.topbar')!.getBoundingClientRect().bottom, height: element.getBoundingClientRect().height, available: element.parentElement!.getBoundingClientRect().height }));
  expect(geometry.top).toBe(geometry.header);
  expect(Math.abs(geometry.height / geometry.available - .9)).toBeLessThan(.01);
  expect(await page.locator('.workspace .conversation-scroll').boundingBox()).toEqual(readingBefore);
  expect(await page.locator('.conversation-map-backdrop').evaluate(element => getComputedStyle(element).backdropFilter)).toBe('none');
  const rootNode = panel.locator(`[data-map-message="${map.messages[0].id}"]`);
  await expect(rootNode).toHaveAttribute('aria-current', 'location');
  const canvasBefore = await panel.locator('.conversation-map-canvas').boundingBox();
  await rootNode.hover();
  await page.waitForTimeout(200);
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  expect(await panel.locator('svg path').evaluateAll(paths => paths.every(path => !/[QC]/.test(path.getAttribute('d') || '')))).toBe(true);
  const initialSelection = await rootNode.evaluate(async element => {
    element.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }));
    await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())));
    return element.getAttribute('aria-pressed');
  });
  expect(initialSelection).toBe('true');
  const detail = panel.getByRole('complementary', { name: '消息内容预览' });
  await expect(detail).toContainText('主对话的长文档');
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  const canvasAfter = await panel.locator('.conversation-map-canvas').boundingBox();
  expect(canvasAfter!.width).toBe(canvasBefore!.width);
  expect(canvasAfter!.height).toBe(canvasBefore!.height);
  expect(canvasAfter!.x).toBeLessThan(canvasBefore!.x);
  const panes = await panel.evaluate(element => {
    const map = element.querySelector('.conversation-map-clip')!.getBoundingClientRect();
    const preview = element.querySelector('.map-message-detail')!.getBoundingClientRect();
    return { mapRight: map.right, previewLeft: preview.left, mapTop: map.top, previewTop: preview.top };
  });
  expect(panes.mapRight).toBe(panes.previewLeft);
  expect(panes.mapTop).toBe(panes.previewTop);
  const separator = panel.getByRole('separator', { name: '调整地图与预览比例' });
  await expect.poll(() => panel.locator('.conversation-map-body').evaluate(element => element.getAnimations().length)).toBe(0);
  const transition = await panel.locator('.conversation-map-body').evaluate(element => ({ property: getComputedStyle(element).transitionProperty, duration: getComputedStyle(element).transitionDuration }));
  expect(transition.property).toBe('grid-template-columns');
  expect(transition.duration).toBe('0.28s');
  expect(await detail.locator('header').evaluate(element => element.getBoundingClientRect().height)).toBeLessThan(36);
  const initialRatio = Number(await separator.getAttribute('aria-valuenow'));
  await separator.hover();
  await expect(separator).toHaveClass(/ready/);
  const handle = await separator.boundingBox();
  await page.mouse.move(handle!.x + handle!.width / 2, handle!.y + 80);
  await page.mouse.down();
  await page.mouse.move(handle!.x + 84, handle!.y + 80, { steps: 5 });
  await page.mouse.up();
  await expect.poll(async () => Number(await separator.getAttribute('aria-valuenow'))).toBeGreaterThan(initialRatio);
  await expect(page.locator('html')).not.toHaveClass(/map-split-resizing/);
  await separator.focus();
  await page.keyboard.press('End');
  await expect.poll(async () => separator.getAttribute('aria-valuenow')).toBe(await separator.getAttribute('aria-valuemax'));
  await page.keyboard.press('Home');
  await expect.poll(async () => separator.getAttribute('aria-valuenow')).toBe(await separator.getAttribute('aria-valuemin'));
  await page.keyboard.press('ArrowRight');
  expect(await page.evaluate(() => Number(localStorage.getItem('mapSplitRatio')))).toBeGreaterThan(0);
  await rootNode.dblclick();
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await expect.poll(() => page.locator('.workspace .conversation-scroll').evaluate(element => element.scrollTop)).toBe(0);
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await toggle.click();
  await rootNode.dblclick();
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await toggle.click();
  let notePreviewRequests = 0;
  page.on('request', request => { if (new URL(request.url()).pathname === `/api/streams/${note.streamId}`) notePreviewRequests++; });
  const branchQuestion = map.messages.find(message => message.id === branch.questionMessageId)!;
  await panel.locator(`[data-map-message="${branchQuestion.id}"]`).click();
  await expect(detail.locator('.map-detail-quote')).toContainText(source.selection_text.slice(0, 2));
  await panel.locator(`[data-map-message="${noteMessage.id}"]`).click();
  await expect(detail.locator('.map-detail-quote')).toContainText(branchSource.selection_text.slice(0, 2));
  await expect(detail.locator('strong')).toHaveText('深层笔记内容');
  const branchNode = panel.locator(`[data-map-message="${branchQuestion.id}"]`);
  const instantSelection = await branchNode.evaluate(async element => {
    element.dispatchEvent(new MouseEvent('click', { bubbles: true, detail: 1 }));
    await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())));
    return element.getAttribute('aria-pressed');
  });
  expect(instantSelection).toBe('true');
  await panel.locator(`[data-map-message="${noteMessage.id}"]`).click();
  await expect(detail.locator('strong')).toHaveText('深层笔记内容');
  expect(notePreviewRequests).toBe(1);
  await detail.getByRole('button', { name: '关闭消息预览' }).click();
  await expect(detail).toHaveCount(0);
  const search = page.getByRole('searchbox', { name: '搜索对话地图' });
  await expect(page.locator('.topbar-map-controls').getByRole('searchbox')).toBeVisible();
  await expect(panel.locator('.conversation-map-toolbar')).toHaveCount(0);
  await search.fill('深层笔记内容');
  await expect(page.locator('.map-search-count')).toHaveText('1 / 1');
  await expect(detail).toContainText('深层笔记内容');
  await expect(detail.locator('strong')).toHaveText('深层笔记内容');
  await expect(detail.locator('.map-preview-match')).toHaveCount(1);
  await expect(panel.locator(`[data-map-message="${noteMessage.id}"]`)).toHaveAttribute('data-search-match', 'true');
  await search.fill('找不到的地图内容');
  await expect(page.locator('.map-search-count')).toHaveText('无结果');
  await page.getByRole('button', { name: '清除地图搜索' }).click();
  await expect(search).toHaveValue('');
  await expect(panel.locator('.conversation-map-toolbar')).toHaveCount(0);
  await search.fill('深层笔记内容');
  await expect(page.locator('.map-search-count')).toHaveText('1 / 1');
  await page.getByRole('button', { name: '打开搜索结果' }).click();
  await expect(page.locator('.branch-dialog')).toHaveCount(2);
  await expect(page.locator(`.top-layer [data-message="${noteMessage.id}"]`)).toContainText('深层笔记内容');
  await expect(page.locator('.top-layer .search-jump-highlight')).toHaveAttribute('data-slot', /.+/);
  await expect(page.locator('.search-jump-highlight')).toHaveCount(0);
  await page.locator('.top-layer').getByRole('button', { name: '主对话', exact: true }).click();
  await expect(page.locator('.branch-dialog')).toHaveCount(0);
  await toggle.click();
  const backdrop = page.getByRole('button', { name: '关闭对话地图', exact: true });
  const backdropBounds = await backdrop.boundingBox();
  await page.mouse.click(backdropBounds!.x + 12, backdropBounds!.y + backdropBounds!.height - 12);
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await expect(panel).toBeHidden();
  await expect(page.getByRole('button', { name: /^文档：/ })).toHaveCount(0);
  await page.getByRole('button', { name: '设置', exact: true }).click();
  await page.getByRole('tab', { name: '通用', exact: true }).click();
  await page.getByRole('checkbox', { name: '窗口背景模糊', exact: true }).check();
  await page.getByRole('button', { name: '回到对话', exact: true }).click();
  await toggle.click();
  await expect(page.locator('.conversation-map-backdrop')).toHaveClass(/blurred/);
  expect(await page.locator('.conversation-map-backdrop').evaluate(element => getComputedStyle(element).backdropFilter)).toBe('blur(3px)');
  await toggle.click();
  await expect(panel).toBeHidden();
});

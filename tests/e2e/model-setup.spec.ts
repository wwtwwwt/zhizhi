import { test, expect } from '@playwright/test';

test('manual wizard skips missing imports, gates key field, checks model and saves only after options', async ({ page, request }) => {
  const name = `引导配置-${Date.now()}`;
  let discovery: any, checked: any;
  let probes=0;
  await page.route('**/api/models/import-sources', route => route.fulfill({json:[]}));
  await page.route('**/api/models/discover', async route => { discovery=route.request().postDataJSON(); await route.fulfill({json:{models:['vendor/gpt-6.1-sol','other-model']}}); });
  await page.route('**/api/models/check', async route => { probes++;checked=route.request().postDataJSON();await route.fulfill({json:{ok:true}}); });
  await page.goto('/settings');
  await page.getByRole('button',{name:'添加模型',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'配置模型',exact:true});
  await expect(dialog.getByLabel('供应商',{exact:true})).toBeVisible();
  await expect(dialog.getByLabel('API Key',{exact:true})).toHaveCount(0);
  await expect(dialog.getByText('手动填写',{exact:true})).toHaveCount(0);
  await dialog.getByLabel('供应商',{exact:true}).selectOption('DeepSeek');
  await expect(dialog.getByLabel('Base URL',{exact:true})).toHaveValue('https://api.deepseek.com');
  await expect(dialog.getByLabel('接口类型',{exact:true})).toHaveValue('chat');
  await dialog.getByLabel('API Key',{exact:true}).fill('test-key');
  await dialog.getByRole('button',{name:'下一步',exact:true}).click();
  await expect(dialog.getByRole('group',{name:'可用模型'})).toBeVisible();
  expect(discovery).toMatchObject({baseUrl:'https://api.deepseek.com',apiKey:'test-key',apiType:'chat'});
  expect(probes).toBe(0);
  await dialog.getByLabel('筛选模型').fill('gpt');
  await expect(dialog.getByRole('button',{name:'other-model',exact:true})).toHaveCount(0);
  await dialog.getByRole('button',{name:'vendor/gpt-6.1-sol',exact:true}).click();
  await dialog.getByRole('button',{name:'下一步',exact:true}).click();
  await expect(dialog.getByText('模型连接正常',{exact:true})).toBeVisible();
  expect(checked).toMatchObject({model:'vendor/gpt-6.1-sol',apiType:'chat'});
  await expect(dialog.getByLabel('显示名称',{exact:true})).toHaveValue('GPT-6.1-Sol');
  await expect(dialog.locator('.model-advanced')).not.toHaveAttribute('open','');
  await dialog.getByLabel('显示名称',{exact:true}).fill(name);
  await dialog.getByLabel('支持图片输入',{exact:true}).check();
  const before=await(await request.get('/api/models')).json();expect(before.some((m:any)=>m.name===name)).toBe(false);
  await dialog.getByRole('button',{name:'保存模型',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  const models=await(await request.get('/api/models')).json(),saved=models.find((m:any)=>m.name===name);
  expect(saved).toMatchObject({model:'vendor/gpt-6.1-sol',baseUrl:'https://api.deepseek.com',hasApiKey:true,apiType:'chat',supportsImages:true});
  await page.getByRole('button',{name:`编辑模型：${name}`,exact:true}).click();
  await expect(dialog.getByLabel('显示名称',{exact:true})).toBeVisible();
  await expect(dialog.getByRole('list',{name:'配置进度'})).toHaveCount(0);
  await dialog.getByRole('button',{name:'清除密钥',exact:true}).click();
  await dialog.getByRole('button',{name:'取消',exact:true}).click();
  const unchanged=await(await request.get('/api/models')).json();expect(unchanged.find((m:any)=>m.id===saved.id).hasApiKey).toBe(true);
  await request.delete(`/api/models/${saved.id}`);
});

test('imports go directly to model selection, never expose keys and failed probes stay editable',async({page})=>{
  await page.setViewportSize({width:900,height:700});
  let discovery:any,checked:any,saved:any,probe=0;
  await page.route('**/api/models/import-sources',route=>route.fulfill({json:[{id:'source-id',source:'Claude Code',baseUrl:'https://example.org',apiType:'messages',authType:'bearer',model:'claude-test'}]}));
  await page.route('**/api/models/discover',async route=>{discovery=route.request().postDataJSON();await route.fulfill({json:{models:['claude-test']}});});
  await page.route('**/api/models/check',async route=>{checked=route.request().postDataJSON();probe++;await route.fulfill(probe===1?{status:502,json:{error:{message:'测试失败，请检查模型 ID'}}}:{json:{ok:true}});});
  await page.route('**/api/models',async route=>{if(route.request().method()==='POST'){saved=route.request().postDataJSON();await route.fulfill({json:{id:'new-model'}});}else await route.continue();});
  await page.goto('/settings');await page.getByRole('button',{name:'添加模型',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'配置模型',exact:true});
  await dialog.getByRole('button',{name:/从 Claude Code 导入/}).click();
  await expect(dialog.getByRole('group',{name:'可用模型'})).toBeVisible();
  await expect(dialog.getByLabel('Base URL',{exact:true})).toHaveCount(0);
  expect(discovery).toMatchObject({importSourceId:'source-id',apiType:'messages',authType:'bearer'});expect(discovery.apiKey).toBeUndefined();
  await dialog.getByRole('button',{name:'下一步',exact:true}).click();await expect(dialog.getByRole('alert')).toContainText('测试失败');
  await dialog.getByLabel('模型 ID',{exact:true}).fill('claude-working');
  await dialog.getByRole('button',{name:'下一步',exact:true}).click();await expect(dialog.getByLabel('显示名称',{exact:true})).toHaveValue('Claude-Working');
  expect(await dialog.locator('.model-editor').evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true);
  expect(checked).toMatchObject({importSourceId:'source-id',model:'claude-working'});
  await dialog.getByRole('button',{name:'保存模型',exact:true}).click();await expect(dialog).toHaveCount(0);
  expect(saved).toMatchObject({importSourceId:'source-id',apiType:'messages',authType:'bearer'});expect(saved.apiKey).toBe('');
});

test('unavailable model listing keeps a manual path and closing never saves',async({page})=>{
  let saved=0;
  await page.route('**/api/models/import-sources',route=>route.fulfill({json:[]}));
  await page.route('**/api/models/discover',route=>route.fulfill({status:502,json:{error:{message:'服务不支持读取模型列表'}}}));
  await page.route('**/api/models/check',route=>route.fulfill({json:{ok:true}}));
  await page.route('**/api/models',async route=>{if(route.request().method()==='POST')saved++;await route.continue();});
  await page.goto('/settings');await page.getByRole('button',{name:'添加模型',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'配置模型',exact:true});
  await dialog.getByLabel('供应商',{exact:true}).selectOption('本机服务（LM Studio）');
  await dialog.getByRole('button',{name:'下一步',exact:true}).click();await expect(dialog.getByRole('alert')).toContainText('不支持');
  await dialog.getByRole('button',{name:'手动填写模型 ID',exact:true}).click();
  await dialog.getByLabel('模型 ID',{exact:true}).fill('local-model');await dialog.getByRole('button',{name:'下一步',exact:true}).click();
  await expect(dialog.getByLabel('显示名称',{exact:true})).toHaveValue('Local-Model');
  await dialog.getByRole('button',{name:'上一步',exact:true}).click();
  await expect(dialog.getByLabel('模型 ID',{exact:true})).toHaveValue('local-model');
  await dialog.getByRole('button',{name:'取消',exact:true}).click();await expect(dialog).toHaveCount(0);expect(saved).toBe(0);
});
